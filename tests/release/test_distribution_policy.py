"""Distribution-boundary tests for the runtime wheel and verification sdist."""

from __future__ import annotations

import tomllib
from tests._repo import REPO_ROOT


def _poetry_metadata() -> dict[str, object]:
    with (REPO_ROOT / "pyproject.toml").open("rb") as handle:
        return tomllib.load(handle)["tool"]["poetry"]


def test_wheel_discovers_only_the_runtime_package() -> None:
    metadata = _poetry_metadata()
    assert metadata["packages"] == [{"include": "reciprocal_robin", "from": "src"}]


def test_verification_material_is_explicitly_sdist_only() -> None:
    metadata = _poetry_metadata()
    includes = metadata["include"]
    assert all(item["format"] == "sdist" for item in includes)
    paths = {item["path"] for item in includes}
    assert {
        "CITATION.cff",
        "PROOF_MANIFEST.json",
        "data",
        "poetry.lock",
        "requirements-verification.txt",
        "scripts",
        "tests",
    } <= paths
    assert ".python-version" not in paths
    assert "pytest.ini" not in paths
    assert "papers" not in paths
    assert "submission" not in paths
    assert "release-logs" not in paths
    assert "LICENSE" in paths
    assert "REPRODUCIBILITY.md" not in paths
    assert "RUNBOOK.md" not in paths
    assert all(not path.startswith("CLEANUP_PASS_") for path in paths)


def test_active_source_contains_no_withdrawn_module() -> None:
    source = REPO_ROOT / "src" / "reciprocal_robin"
    assert not (source / "withdrawn.py").exists()
    assert (source / "ca_grid.py").is_file()
    assert not (source / "compat.py").exists()


def test_public_code_tree_contains_no_manuscript_sources() -> None:
    assert not (REPO_ROOT / "papers").exists()
    assert not (REPO_ROOT / "submission").exists()
    assert not (REPO_ROOT / "CITATION_AUDIT.md").exists()
    assert not (REPO_ROOT / "REFERENCE_DISCIPLINE_AUDIT.md").exists()
    release_support = (REPO_ROOT / "scripts" / "release_support.py").read_text(encoding="utf-8")
    assert "PAPERS_DIR" not in release_support


def test_public_release_uses_mit_license() -> None:
    metadata = _poetry_metadata()
    assert metadata["license"] == "MIT"
    license_text = (REPO_ROOT / "LICENSE").read_text(encoding="utf-8")
    assert license_text.startswith("MIT License\n")
    citation = (REPO_ROOT / "CITATION.cff").read_text(encoding="utf-8")
    assert "license: MIT" in citation


def test_release_build_toolchain_is_exactly_pinned() -> None:
    with (REPO_ROOT / "pyproject.toml").open("rb") as handle:
        pyproject = tomllib.load(handle)
    assert pyproject["tool"]["poetry"]["requires-poetry"] == "==2.3.3"
    assert pyproject["build-system"] == {
        "requires": ["poetry-core==2.3.2"],
        "build-backend": "poetry.core.masonry.api",
    }
    header = (REPO_ROOT / "poetry.lock").read_text(encoding="utf-8").splitlines()[0]
    assert header == (
        "# This file is automatically @generated by Poetry 2.3.3 "
        "and should not be changed by hand."
    )
